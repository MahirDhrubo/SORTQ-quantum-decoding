"""Test 2a, Step 2: generate round_wiring.sv (and round_wiring_pkg.sv) from results/test1c/engine_params.json.
Never edit the generated files by hand.

Base edge k (0..34, order of engine_params 'base_edge_table_round5'): check type Z, error type t, round offset o,
shift s = (sa, sb). Check at position x of check round r is connected through base edge k to the error of type t,
home round r - o, position x + s (Z12 x Z6, index a * 6 + b), on that type's edge slot j (index of (o, s) in
engine_params 'error_types'[t]['edges']). Every (type, slot) is exactly one base edge (35 = sum of type weights).

Error-side buses are grouped by offset: offset-0 base edges (NE0) belong to errors homed in the check round,
offset-1 base edges (NE1) to errors homed one round earlier. K_ROUNDS (1..4) check rounds are wired side by side
(round r + ck uses the offset-0 edges of home r + ck and the offset-1 edges of home r + ck - 1); the wiring of one
check round does not depend on the others, so the K copies are identical.

Test 2e (sortq build): sizes come from engine_params (group structure Z_NA x Z_NB, base-edge table of the bulk reference
round, bulk error types, DVMAX = largest bulk type weight); for the gross code the output is unchanged.

Usage: python gen_round_wiring.py [engine_params.json] [outdir]
"""
import sys, os, json

HERE = os.path.dirname(os.path.abspath(__file__))
NA, NB = 12, 6                        # overwritten by load() from engine_params group.structure
DVMAX = 6


def load(path):
    global NA, NB, DVMAX
    d = json.load(open(path))
    NA, NB = d["group"].get("structure", [12, 6])
    be = d.get("base_edge_table", d.get("base_edge_table_round5"))
    types = {t["type"]: t for t in d["error_types"] if t.get("in_bulk_template", True)}
    tnames = sorted(types)
    DVMAX = max(types[t]["weight"] for t in tnames)
    edges = []
    for k, e in enumerate(be):
        t = e["error_type"]; o = e["round_offset"]; s = (e["shift_a"], e["shift_b"])
        slots = [j for j, x in enumerate(types[t]["edges"]) if (x["round_offset"], x["shift_a"], x["shift_b"]) == (o,) + s]
        assert len(slots) == 1, f"base edge {k} matches {len(slots)} slots of {t}"
        edges.append(dict(k=k, t=t, ti=tnames.index(t), o=o, sa=s[0], sb=s[1], slot=slots[0]))
    assert len(edges) == sum(types[t]["weight"] for t in tnames), "base edges != sum of bulk type weights"
    assert len({(e["t"], e["slot"]) for e in edges}) == len(edges), "a (type, slot) appears twice"
    e0 = [e for e in edges if e["o"] == 0]; e1 = [e for e in edges if e["o"] == 1]
    for i, e in enumerate(e0): e["idx"] = i
    for i, e in enumerate(e1): e["idx"] = i
    return d, edges, e0, e1, tnames, types


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "results", "test1c", "engine_params.json")
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "rtl")
    d, edges, e0, e1, tnames, types = load(src)
    NE0, NE1 = len(e0), len(e1)
    hdr = (f"// GENERATED by hw/gen/gen_round_wiring.py from {os.path.relpath(src, out)} — do not edit by hand.\n")

    # ---------------------------------------------------------------- package: base-edge table
    P = [hdr, "package round_wiring_pkg;",
         f"  localparam int NPOS = {NA * NB};   // positions in Z{NA} x Z{NB}, index a * {NB} + b",
         f"  localparam int NBASE = {len(edges)};  // base edges per check (check degree in the bulk)",
         f"  localparam int NE0 = {NE0};    // offset-0 base edges (errors homed in the check round)",
         f"  localparam int NE1 = {NE1};    // offset-1 base edges (errors homed one round earlier)",
         f"  localparam int NTYPES = {len(tnames)};", f"  localparam int DVMAX = {DVMAX};"]
    def arr(name, vals, w="int"):
        P.append(f"  localparam {w} {name} [{len(vals)}] = '{{{', '.join(str(v) for v in vals)}}};")
    arr("BE_TYPE", [e["ti"] for e in edges]); arr("BE_OFF", [e["o"] for e in edges])
    arr("BE_SA", [e["sa"] for e in edges]); arr("BE_SB", [e["sb"] for e in edges])
    arr("BE_SLOT", [e["slot"] for e in edges]); arr("BE_IDX", [e["idx"] for e in edges])
    arr("TYPE_DEG", [types[t]["weight"] for t in tnames])
    ts = [[-1] * DVMAX for _ in tnames]
    for e in edges: ts[e["ti"]][e["slot"]] = e["k"]
    P.append(f"  localparam int TS_EDGE [{len(tnames)}][{DVMAX}] = '{{" +
             ", ".join("'{" + ", ".join(map(str, r)) + "}" for r in ts) + "};  // (type, slot) -> base edge, -1 = none")
    P.append("  // base edges by type: " + "; ".join(f"{t}: " + ",".join(str(e['k']) for e in edges if e['t'] == t) for t in tnames))
    # ---- leg-start (init) gating, derived from the round offsets only (sweep order = increasing check round).
    # An error homed h with offsets 0..omax is updated in layers h .. h + omax ("group" d = layer - h).
    # CNU of layer r, edge offset o: reads the v2c of the error homed r - o; that error was already updated in this
    #   iteration iff it has a layer < r, i.e. o >= 1. o == 0 -> not yet updated -> at init the input is the prior.
    # VNU of group d, slot offset o: its c2v comes from check round h + o; fresh iff h + o <= h + d (that layer has
    #   run in this iteration). o > d -> stale at init -> taken as 0.
    omax = {t: max(x["round_offset"] for x in types[t]["edges"]) for t in tnames}
    assert max(omax.values()) <= 1, "round_step has groups d = 0, 1 only (offsets 0 and 1)"
    def bits(vals): return "'{" + ", ".join(f"1'b{int(v)}" for v in vals) + "}"
    P.append(f"  localparam bit INIT_CNU_PRIOR [{len(edges)}] = {bits(e['o'] == 0 for e in edges)};"
             "  // CNU input = prior at init")
    for d, name in ((0, "INIT_ZERO_CUR"), (1, "INIT_ZERO_PREV")):
        rows = []
        for t in tnames:
            r = [0] * DVMAX
            for e in edges:
                if e["t"] == t: r[e["slot"]] = int(e["o"] > d)
            rows.append(bits(r))
        P.append(f"  localparam bit {name} [{len(tnames)}][{DVMAX}] = '{{{', '.join(rows)}}};"
                 f"  // VNU group d = {d}: c2v slot taken as 0 at init")
    P.append(f"  localparam bit HAS_PREV [{len(tnames)}] = {bits(omax[t] >= 1 for t in tnames)};"
             "  // type also updated in layer home + 1")
    P.append("endpackage")
    open(os.path.join(out, "round_wiring_pkg.sv"), "w").write("\n".join(P) + "\n")

    # ---------------------------------------------------------------- module: hard wiring
    M = [hdr,
         f"// One check round (x K_ROUNDS): {NA * NB} checks x {len(edges)} base edges = {NA * NB * len(edges):,} edges, both directions.",
         "//   cnu_in [ck][x][k]           <- v2c_o0/o1 [ck][idx(k)][x + s_k]   (error -> check)",
         "//   c2v_o0/o1 [ck][idx(k)][p]   <- cnu_out [ck][p - s_k][k]           (check -> error)",
         "module round_wiring",
         "  import round_wiring_pkg::*;",
         "#(",
         "  parameter int W = 5,          // payload width (sign + magnitude for messages)",
         "  parameter int K_ROUNDS = 1    // check rounds wired side by side (1..4)",
         ") (",
         "  input  logic [K_ROUNDS-1:0][NE0-1:0][NPOS-1:0][W-1:0]   v2c_o0,",
         "  input  logic [K_ROUNDS-1:0][NE1-1:0][NPOS-1:0][W-1:0]   v2c_o1,",
         "  output logic [K_ROUNDS-1:0][NPOS-1:0][NBASE-1:0][W-1:0] cnu_in,",
         "  input  logic [K_ROUNDS-1:0][NPOS-1:0][NBASE-1:0][W-1:0] cnu_out,",
         "  output logic [K_ROUNDS-1:0][NE0-1:0][NPOS-1:0][W-1:0]   c2v_o0,",
         "  output logic [K_ROUNDS-1:0][NE1-1:0][NPOS-1:0][W-1:0]   c2v_o1",
         ");",
         "  for (genvar ck = 0; ck < K_ROUNDS; ck++) begin : g_round"]
    n = 0
    for x in range(NA * NB):
        xa, xb = divmod(x, NB)
        for e in edges:
            p = ((xa + e["sa"]) % NA) * NB + (xb + e["sb"]) % NB
            bus = "o0" if e["o"] == 0 else "o1"
            M.append(f"    assign cnu_in[ck][{x}][{e['k']}] = v2c_{bus}[ck][{e['idx']}][{p}];"
                     f"  // {e['t']} slot {e['slot']}")
            M.append(f"    assign c2v_{bus}[ck][{e['idx']}][{p}] = cnu_out[ck][{x}][{e['k']}];")
            n += 1
    M += ["  end", "endmodule"]
    open(os.path.join(out, "round_wiring.sv"), "w").write("\n".join(M) + "\n")
    print(f"round_wiring.sv: {n} edges per check round (x2 directions), NE0 = {NE0}, NE1 = {NE1}; "
          f"round_wiring_pkg.sv written to {out}")


if __name__ == "__main__":
    main()
