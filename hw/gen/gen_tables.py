"""Test 2a: generate engine_tables_pkg.sv — boundary type sets (engine_params) and the logical-observable ROM.
  TP_FIRST / TP_LAST: error types present at home round 0 / at the final round R (bit t = type T0t);
                      bulk rounds have all 10 types (engine_params 'error_types_per_home_round').
  OBS_ROM[t][p]:      12-bit logical-observable flip mask of the error of type t at position p. Measured to be
                      independent of the home round (asserted here on the circuit given).
Usage: python gen_tables.py <circuit.stim> [engine_params.json] [outdir]
Test 2e: decoder basis and sizes from engine_params (check_type, group.structure); unchanged for the gross-code X decoder.
"""
import sys, os, json
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, "..", "..", "scripts"))


def main():
    circ = sys.argv[1]
    epf = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "..", "results", "test1c", "engine_params.json")
    out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(HERE, "..", "rtl")
    from dem_tools import decoder_problem
    from labels import labels
    ep = json.load(open(epf)); P = decoder_problem(circ, ep.get("check_type", "Z")); L = labels(P, ep)
    NA_, NB_ = ep["group"].get("structure", [12, 6]); NPOS = NA_ * NB_
    tn = L["tnames"]
    per = ep["error_types_per_home_round"]; last = str(max(int(k) for k in per))
    bits = lambda names: sum(1 << tn.index(t) for t in names)
    tp_first, tp_last = bits(per["0"]), bits(per[last])
    assert all(bits(per[k]) == (1 << len(tn)) - 1 for k in per if k not in ("0", last)), "bulk rounds must have all types"
    O = P["O"]; O = np.asarray(O.todense() if hasattr(O, "todense") else O).astype(int); nobs = O.shape[0]
    rom = {}
    for j in range(O.shape[1]):
        key = (int(L["col_t"][j]), int(L["col_p"][j])); v = int("".join(str(b) for b in O[::-1, j]), 2)
        assert rom.setdefault(key, v) == v, "observable mask depends on the home round"
    assert len(rom) == len(tn) * NPOS
    lines = [f"// GENERATED by hw/gen/gen_tables.py — do not edit by hand.",
             f"// circuit: {os.path.basename(circ)}", "package engine_tables_pkg;",
             f"  localparam int NOBS = {nobs};",
             f"  localparam logic [{len(tn) - 1}:0] TP_FIRST = {len(tn)}'b{tp_first:0{len(tn)}b};  // types at home round 0",
             f"  localparam logic [{len(tn) - 1}:0] TP_LAST  = {len(tn)}'b{tp_last:0{len(tn)}b};  // types at the final round",
             f"  localparam logic [NOBS-1:0] OBS_ROM [{len(tn)}][{NPOS}] = '{{"]
    rows = []
    for t in range(len(tn)):
        rows.append("    '{" + ", ".join(f"{nobs}'h{rom[(t, p)]:0{(nobs + 3) // 4}x}" for p in range(NPOS)) + "}")
    lines.append(",\n".join(rows)); lines += ["  };", "endpackage"]
    open(os.path.join(out, "engine_tables_pkg.sv"), "w").write("\n".join(lines) + "\n")
    print(f"engine_tables_pkg.sv: NOBS {nobs}, TP_FIRST {tp_first:0{len(tn)}b}, TP_LAST {tp_last:0{len(tn)}b}, OBS_ROM {len(tn)} x {NPOS} "
          f"(home-round independent: asserted on {O.shape[1]} columns)")


if __name__ == "__main__":
    main()
