"""Test 3d: engine_top_pf2_sim.sv = engine_top_pf2.sv with the 720 gamma lanes in LOAD mode (LFSR_MODE = 0), loaded
from two new ports (g8_ld, g8_ld_data[type][pos]). Nothing else changes; the diff is printed.
Usage: python mk_sim_engine.py <engine_top_pf2.sv> <out.sv>
"""
import sys, difflib
src, dst = sys.argv[1], sys.argv[2]
a = open(src).read(); s = a


def rep(x, y):
    global s
    assert s.count(x) == 1, (x, s.count(x)); s = s.replace(x, y)


rep("module engine_top_pf2\n", "module engine_top_pf2_sim\n")
rep("""  input  logic [MW-1:0]       pr_wdata,
""", """  input  logic [MW-1:0]       pr_wdata,
  // Test 3d: gamma lanes in LOAD mode (testbench supplies the software g8 of each leg)
  input  logic                                g8_ld,
  input  logic [NTYPES-1:0][NPOS-1:0][3:0]    g8_ld_data,
""")
rep("gamma_src #(.LFSR_MODE(1'b1),", "gamma_src #(.LFSR_MODE(1'b0),")
rep(".load(1'b0), .load_g8('0),", ".load(g8_ld), .load_g8(g8_ld_data[t][p]),")
s = "// GENERATED by hw/sim3d/mk_sim_engine.py from engine_top_pf2.sv (Test 3d, simulation only).\n" + s
open(dst, "w").write(s)
sys.stdout.writelines(difflib.unified_diff(a.splitlines(True), s.splitlines(True), "engine_top_pf2.sv", dst))
