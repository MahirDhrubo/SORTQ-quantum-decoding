"""Table IV: p99.9 latency and utilization of each design at its measured iteration time, from the test1e_criteria
queue model unchanged (10^7 jobs resampled with seed 20261112, T = 12 us per job, overhead 200 ns, K = 18,080 =
the decoder's own cap, no extra cap), on existing traces (no decoding).
  fully parallel   float flood traces (Test 1b)              at 24 ns per iteration (IBM, published)
  SORTQ sweep      int4.2.8 sweep traces (Test 1b)           at 188.2 ns (pf2fix: 26 cycles x 7.24 ns)
  SORTQ red-black  rb13 int4.2.8 traces (Test 1g; p = 0.001 eval run) at 61.88 ns (13 cycles x 4.76 ns);
                   p = 0.003 also on the fresh (Test 1h step 2) and pooled (Test 1g + 1h) traces
Output: results/eval/latency.json, latency.md.   Usage: python eval_latency.py
"""
import os, json
import test1e_criteria as C
from test1e_queue import Sim

R, T_US = os.environ.get("RESULTS_ROOT", C.ROOT), 12.0   # RESULTS_ROOT: run outside the server
DESIGNS = [("fully parallel (float flood)", 24.0, R + "/test1b/p{p}_float_flood.npz"),
           ("SORTQ sweep (int4.2.8 sweep)", 188.2, R + "/test1b/p{p}_int4.2.8_sweep.npz"),
           ("SORTQ red-black (rb13 int4.2.8)", 61.88, None)]
RB = {"0.003": R + "/test1g/p0.003_rb13.npz", "0.002": R + "/test1g/p0.002_rb13.npz",
      "0.001": R + "/test1g/p001/p0.001_rb13.npz"}
EXTRA = [("SORTQ red-black, fresh shots", 61.88, "0.003", R + "/test1h/step2/p0.003_rb13_int4.npz"),
         ("SORTQ red-black, pooled", 61.88, "0.003", R + "/test1h/criteria_robust/traces/pooled_p0.003_sweep.npz")]


def one(name, t, p, f):
    r = Sim(C.seq(f)).run(C.K, t, C.OV, T_US, full=True)
    row = dict(design=name, p=p, ns_per_iter=t, trace=os.path.relpath(f, R), util=float(r["util"]),
               lat_p999_us=float(r["lat_p999_us"]), queue_max=int(r["queue_max"]),
               meets_c=bool(r["util"] < 1 and r["lat_p999_us"] < 1000), meets_b=bool(r["util"] < 1 and r["lat_p999_us"] < 100))
    print(json.dumps(row), flush=True)
    return row


rows = [one(n, t, p, f.format(p=p) if f else RB[p]) for n, t, f in DESIGNS for p in ("0.003", "0.002", "0.001")]
rows += [one(n, t, p, f) for n, t, p, f in EXTRA]
os.makedirs(R + "/eval", exist_ok=True)
json.dump(dict(rows=rows, T_us=T_US, jobs=C.JOBS, seed=C.SEED, K=C.K, overhead_ns=C.OV),
          open(R + "/eval/latency.json", "w"), indent=1)
L = ["# Table IV: p99.9 latency at the measured iteration time", "",
     "Generated by `scripts/eval_latency.py`: test1e_criteria queue model unchanged (10^7 jobs, seed 20261112, T = 12 µs, "
     "overhead 200 ns, K = 18,080), existing traces, no decoding.", "",
     "| Design (ns / iteration) | p = 0.003 | p = 0.002 | p = 0.001 |", "|---|---|---|---|"]
for n, t, _ in DESIGNS:
    c = {r["p"]: r for r in rows if r["design"] == n}
    L.append(f"| {n} ({t:g} ns) | " + " | ".join(f"{c[p]['lat_p999_us']:.1f} µs (util {c[p]['util']:.3f})"
                                                  for p in ("0.003", "0.002", "0.001")) + " |")
L += ["", "Red-black at p = 0.003 on other shot sets:", "", "| Trace | p99.9 latency | Utilization | Queue max |", "|---|---|---|---|"]
for r in rows:
    if r["design"].startswith("SORTQ red-black") and r["p"] == "0.003":
        L.append(f"| {r['design']} (`{r['trace']}`) | {r['lat_p999_us']:.1f} µs | {r['util']:.3f} | {r['queue_max']} |")
open(R + "/eval/latency.md", "w").write("\n".join(L) + "\n")
