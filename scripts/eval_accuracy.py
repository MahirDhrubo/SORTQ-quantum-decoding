"""Eval tasks 1 + 2: paired accuracy on the Test 1b shots, from existing per-shot traces only (no decoding here).

Traces (all on the same Test 1b shots: sampler seed 20261111, Test 1b batch x workers):
  results/test1b/p{p}_float_flood.npz, _float_sweep, _int4.2.8_flood, _int4.2.8_sweep   (Test 1b)
  results/test1g/p{p}_rb13.npz                       p = 0.003, 0.002 (Test 1g)
  results/test1g/p001/p0.001_rb13.npz, _sweep.npz    p = 0.001 (eval task 2; sweep only as a shot-identity check)
Pairs: p = 0.003 / 0.002: rb13 int4 vs float flood, rb13 int4 vs int4 flood, int4 sweep vs float flood,
       float sweep vs float flood;   p = 0.001: rb13 int4 vs float flood, rb13 int4 vs int4 sweep.
McNemar: exact two-sided binomial on the discordant pairs (test1b_quant.mcnemar, as in Tests 1b-1g).
Criteria (task 2): results/test1g/p001/criteria/criteria.json (test1e_criteria model, unchanged).
Output: results/eval/accuracy.md, accuracy.json, criteria_rb_p001.md.   Usage: python eval_accuracy.py
"""
import os, json
import numpy as np
from test1b_quant import mcnemar

IDEAS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
R = os.path.join(IDEAS, "results")
OUT = os.path.join(R, "eval")
NAMES = {"float_flood": "float flood", "float_sweep": "float sweep", "int4_flood": "int4.2.8 flood",
         "int4_sweep": "int4.2.8 sweep", "rb13": "int4.2.8 rb13"}
PAIRS = {"0.003": [("rb13", "float_flood"), ("rb13", "int4_flood"), ("int4_sweep", "float_flood"),
                   ("float_sweep", "float_flood")],
         "0.001": [("rb13", "float_flood"), ("rb13", "int4_sweep")]}
PAIRS["0.002"] = PAIRS["0.003"]


def paths(p):
    t1b = lambda s: os.path.join(R, "test1b", f"p{p}_{s}.npz")
    d = dict(float_flood=t1b("float_flood"), float_sweep=t1b("float_sweep"),
             int4_flood=t1b("int4.2.8_flood"), int4_sweep=t1b("int4.2.8_sweep"))
    d["rb13"] = os.path.join(R, "test1g", "p001" if p == "0.001" else "", f"p{p}_rb13.npz")
    return d


def main():
    os.makedirs(OUT, exist_ok=True)
    res = {}
    for p in ("0.003", "0.002", "0.001"):
        P = paths(p)
        if not os.path.exists(P["rb13"]):
            print("missing", P["rb13"]); continue
        D = {k: dict(np.load(v)) for k, v in P.items()}
        n = {k: len(d["logical_fail"]) for k, d in D.items()}
        if len(set(n.values())) != 1:     # e.g. the p = 0.001 run still in progress (traces are saved as it goes)
            print("shot counts differ, skipped:", p, n); continue
        r = dict(shots=n["rb13"], designs={}, pairs=[])
        if p == "0.001":   # shot identity: the sweep decoded in the same run must equal Test 1b's int4 sweep
            s = np.load(os.path.join(R, "test1g", "p001", "p0.001_sweep.npz")); e = D["int4_sweep"]
            r["identity_check"] = {k: int(np.sum(s[k] != e[k])) for k in ("iterations", "success", "logical_fail")}
        else:
            r["identity_check"] = json.load(open(os.path.join(R, "test1g", "report.json")))[f"p{p}"]["sweep_vs_test1b"]
        for k, d in D.items():
            if p == "0.001" and k not in ("rb13", "float_flood", "int4_sweep"):
                continue
            fl, it = d["logical_fail"], d["iterations"]
            r["designs"][k] = dict(fails=int(fl.sum()), ler=float(fl.mean()), mean_it=float(it.mean()),
                                   p99_9=float(np.percentile(it, 99.9)), max_it=int(it.max()),
                                   not_converged=int((~d["success"]).sum()))
        for a, b in PAIRS[p]:
            fa, fb = D[a]["logical_fail"], D[b]["logical_fail"]
            oa, ob = int(np.sum(fa & ~fb)), int(np.sum(~fa & fb))
            r["pairs"].append(dict(A=a, B=b, both=int(np.sum(fa & fb)), only_A=oa, only_B=ob, mcnemar_p=mcnemar(oa, ob)))
        res[p] = r
    json.dump(res, open(os.path.join(OUT, "accuracy.json"), "w"), indent=1)
    write_md(res)
    crit = os.path.join(R, "test1g", "p001", "criteria", "criteria.json")
    if os.path.exists(crit):
        write_crit(json.load(open(crit)))
    print(json.dumps(res, indent=1))


def ler(x):
    return f"{x:.2e}"


def write_md(res):
    L = ["# Paired accuracy vs the reference (Test 1b shots)", "",
         "Generated by `scripts/eval_accuracy.py` from existing per-shot traces (measured).", "",
         "## Setup",
         "- **Shots:** the Test 1b shots (12-round [[144,12,12]] memory_Z circuit, X decoder, uniform circuit noise; "
         "sampler seed 20261111, Test 1b batch × workers): 168,000 at p = 0.003, 600,000 at p = 0.002 and 0.001. "
         "Every design decodes the same shots, so all comparisons are paired.",
         "- **Decoder settings (all designs):** Relay-BP, alpha = 1, S = 1, gamma0 = 0.125, gamma interval (−0.226, 0.622), "
         "pre_iter 80, 300 legs × 60 (cap 18,080 iterations).",
         "- **Designs:**",
         "  - float flood (the reference), float sweep, int4.2.8 flood, int4.2.8 sweep: Test 1b;",
         "  - int4.2.8 rb13 (red-black round order 0, 2, …, 12, 1, …, 11; the engine_top_rb schedule): Test 1g "
         "(p = 0.003, 0.002) and this task (p = 0.001).",
         "- **Identity of the shots** (the sweep decoded alongside rb13 vs Test 1b's int4.2.8 sweep, shot by shot): "]
    for p, r in res.items():
        ic = r["identity_check"]
        L.append(f"  - p = {p}: " + ", ".join(f"{k.replace('_differ', '')} differ on {v} shots" for k, v in ic.items() if k != "shots_compared"))
    L += ["- **McNemar:** exact two-sided binomial test on the shots where exactly one design fails "
          "(only A vs only B), as in Tests 1b–1g.", "",
          "## Failures, LER and iterations", "",
          "| p | Shots | Design | Failures | LER | Mean iterations | p99.9 / max iterations | Not converged |",
          "|---|---|---|---|---|---|---|---|"]
    for p, r in res.items():
        for k in ("float_flood", "float_sweep", "int4_flood", "int4_sweep", "rb13"):
            if k in r["designs"]:
                d = r["designs"][k]
                L.append(f"| {p} | {r['shots']:,} | {NAMES[k]} | {d['fails']} | {ler(d['ler'])} | {d['mean_it']:.2f} | "
                         f"{d['p99_9']:.0f} / {d['max_it']:,} | {d['not_converged']} |")
    L += ["", "## Paired comparisons", "",
          "| p | A | B | Failures A / B | Both | Only A | Only B | McNemar p |", "|---|---|---|---|---|---|---|---|"]
    for p, r in res.items():
        for q in r["pairs"]:
            fa, fb = r["designs"][q["A"]]["fails"], r["designs"][q["B"]]["fails"]
            L.append(f"| {p} | {NAMES[q['A']]} | {NAMES[q['B']]} | {fa} / {fb} | {q['both']} | {q['only_A']} | "
                     f"{q['only_B']} | {q['mcnemar_p']:.3g} |")
    L.append("")
    open(os.path.join(OUT, "accuracy.md"), "w").write("\n".join(L))


def write_crit(J):
    L = ["# Real-time criteria targets: rb13 int4.2.8 at p = 0.001", "",
         "Generated by `scripts/eval_accuracy.py` from `results/test1g/p001/criteria/criteria.json` "
         "(`test1e_criteria.py` model unchanged: 10^7 jobs resampled with seed 20261112, K = 18,080, overhead 200 ns; "
         "trace = the p = 0.001 rb13 run of this task, 600,000 shots, 13 rounds per job).", "",
         "Largest ns per 13-round iteration that meets each criterion:",
         "a = utilization < 0.7 and queue max < 1000 jobs; b = p99.9 latency < 100 µs; c = p99.9 < 1 ms; d = p99.9 < 10 ms.", "",
         "| T (µs per job) | Criterion | Largest t_iter (ns) | Per round (ns) | Binding | Utilization | p99.9 latency (µs) | Queue max |",
         "|---|---|---|---|---|---|---|---|"]
    for r in J["rows"]:
        t = r["t_iter_max_ns"]
        L.append(f"| {r['T_us']:g} | {r['crit']} | {t:.0f} | {r['per_round_ns']:.1f} | {r['binding']} | {r['util']:.3f} | "
                 f"{r['lat_p999_us']:.1f} | {r['queue_max']} |" if t else
                 f"| {r['T_us']:g} | {r['crit']} | none | | {r['binding']} | | | |")
    L.append("")
    open(os.path.join(OUT, "criteria_rb_p001.md"), "w").write("\n".join(L))


if __name__ == "__main__":
    main()
